export function useApplicantT() {
  const { language } = useI18n()
  const messages = { en, ru, kk }[language]
  return (key: Key, params?: Record<string, string | number>) =>
    messages[key].replace(/\{(\w+)\}/g, (match, name: string) => String(params?.[name] ?? match))
}
