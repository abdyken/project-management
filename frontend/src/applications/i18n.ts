export type ApplicationsKey = Key

export function useApplicationsT() {
  const { language } = useI18n()
  const messages = { en, ru, kk }[language]
  return (key: Key, params?: Record<string, string | number>) =>
    messages[key].replace(/\{(\w+)\}/g, (match, name: string) => String(params?.[name] ?? match))
}

// Translated text for an API error code on the applicant pages.
export function applicationsErrorKey(code: string | undefined, status?: number): Key {
  switch (code) {
    case "APPLICATIONS_UNAVAILABLE":
      return "unavailable"
    case "APPLICATION_EXISTS":
      return "exists"
    case "TOO_MANY_APPLICATIONS":
      return "tooMany"
    case "UNSUPPORTED_FILE_TYPE":
    case "EMPTY_FILE":
      return "fileType"
    case "FILE_TOO_LARGE":
    case "APPLICATION_FULL":
      return "fileTooLarge"
    case "TOO_MANY_DOCUMENTS":
      return "tooManyDocuments"
    case "ACCOUNT_STORAGE_FULL":
      return "accountFull"
    case "UPLOADS_PAUSED":
      return "uploadsPaused"
    case "APPLICATION_INCOMPLETE":
      return "incomplete"
    case "APPLICATION_LOCKED":
      return "locked"
    case "APPLICATION_NOT_FOUND":
      return "notFound"
    case "INVALID_REQUEST":
      return "invalid"
    default:
      return status === 413 ? "fileTooLarge" : "error"
  }
}
